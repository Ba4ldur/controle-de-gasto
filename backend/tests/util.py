def gerar_xlsx(linhas: list[list]) -> bytes:
    wb = openpyxl.Workbook()
    ws = wb.active
    for linha in linhas:
        ws.append(linha)
    buffer = io.BytesIO()
    wb.save(buffer)
    return buffer.getvalue()


def upload(client, empresa_id, conta_id, nome, conteudo: bytes, preview=False):
    rota = f"/api/empresas/{empresa_id}/importacoes" + ("/preview" if preview else "")
    return client.post(
        rota,
        files={"arquivo": (nome, conteudo, "application/octet-stream")},
        data={"conta_id": conta_id},
    )
